const urlParams = typeof window !== 'undefined' ? new URLSearchParams(window.location.search) : null;
let currentLang = (urlParams && (urlParams.get('lang') === 'ar' || urlParams.get('lang') === 'en')) 
  ? urlParams.get('lang') 
  : (typeof localStorage !== 'undefined' ? localStorage.getItem('aurora_lang') || 'en' : 'en');

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'ar') return;
  if (lang === currentLang) return;
  document.body.classList.add('is-switching-lang');
  setTimeout(() => {
    currentLang = lang;
    localStorage.setItem('aurora_lang', currentLang);
    applyLanguage(currentLang);
    requestAnimationFrame(() => {
      setTimeout(() => {
        document.body.classList.remove('is-switching-lang');
      }, 50);
    });
  }, 130);
}

export function toggleLanguage() {
  const nextLang = currentLang === 'en' ? 'ar' : 'en';
  setLanguage(nextLang);
  return nextLang;
}

export function t(key) {
  const dict = translations[currentLang] || translations.en;
  return dict[key] || translations.en[key] || key;
}

export function applyLanguage(lang) {
  const isArabic = lang === 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = isArabic ? 'rtl' : 'ltr';

  // Translate all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const hasStar = el.querySelector('.required-star');
      if (hasStar) {
        el.innerHTML = `${t(key)} <span class="required-star">*</span>`;
      } else {
        el.textContent = t(key);
      }
    }
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      el.setAttribute('placeholder', t(key));
    }
  });

  // Language toggle button label
  const langLabel = document.getElementById('langToggleLabel');
  if (langLabel) {
    langLabel.textContent = isArabic ? 'English' : 'عربي';
  }
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.textContent = isArabic ? 'English' : 'عربي';
  });

  // Dispatch global synchronous event for instant UI re-rendering (Requirement 4.4: 0ms lag)
  window.dispatchEvent(new CustomEvent('aurora:languageChange', { detail: { lang, isArabic } }));
}

